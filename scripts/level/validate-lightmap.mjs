#!/usr/bin/env node
/** Coverage-only validation artifact. Never delivers a level or runs production lighting. */
import fs from 'node:fs/promises';
import path from 'node:path';
import { NodeIO, Logger, PropertyType } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { prune } from '@gltf-transform/functions';
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer';
import { bakeWithBlender } from './bakers/blender-cycles.mjs';
import { buildLodTiers } from './pipeline/lod.mjs';
import { compressTextures, addLightmapTexture } from './pipeline/textures.mjs';
import { compressLevelGeometry } from './pipeline/compress-geometry.mjs';
import { writeManifest } from './pipeline/manifest.mjs';
import { auditAtlasCoverage } from './pipeline/atlas-coverage.mjs';
import { parseArgs } from '../lib/out.mjs';
const args=parseArgs();
const id=String(args.level??'');
if(!/^[a-z0-9-]+$/.test(id))throw Error('need --level <id>');
const build=path.resolve('levels',id,'build'),outDir=path.join(build,'uv_validation');
const progress=m=>console.log(new Date().toISOString(),m);
await Promise.all([MeshoptEncoder.ready,MeshoptDecoder.ready]);
const io=new NodeIO().setLogger(new Logger(Logger.Verbosity.SILENT)).registerExtensions(ALL_EXTENSIONS).registerDependencies({'meshopt.encoder':MeshoptEncoder,'meshopt.decoder':MeshoptDecoder});
let doc=await io.read(path.join(build,'stage1.glb'));
const bake=JSON.parse(await fs.readFile(path.join(build,'bake.json'),'utf8'));
bake.settings.lightmap={...bake.settings.lightmap,size:4096,texelsPerMeter:12,maxAtlases:32,samples:1,noiseThreshold:0};
await fs.mkdir(outDir,{recursive:true});
const result=await bakeWithBlender({io,doc,bake,outDir,coverageOnly:true,onProgress:progress});
if(result.lightmapStats.coverageOnly!==true)throw Error('validation requires coverage-only output');
doc=result.doc;
await io.write(path.join(outDir,'uncompressed.glb'),doc);
progress('building actual exported LODs');
const lodStats=await buildLodTiers({lod1Ratio:bake.settings.lod?.lod1Ratio??.4,lod2Ratio:bake.settings.lod?.lod2Ratio??.15})(doc);
await io.write(path.join(outDir,'lod.glb'),doc);
progress('encoding material textures and diagnostic atlas pages');
await compressTextures({colorMode:bake.settings.textures?.colorMode??'etc1s',dataMode:'uastc',maxSize:bake.settings.textures?.maxSize??2048,onProgress:progress})(doc);
const images=[];
for(const png of result.lightmapPngs)images.push(await addLightmapTexture(doc,png,{onProgress:progress}));
await doc.transform(compressLevelGeometry({encoder:MeshoptEncoder}));
writeManifest({bake,lodStats,lightmapImage:images,lightmapStats:result.lightmapStats,skyIndices:{},generator:{tool:'thaikit-coverage-validation',version:'1'},liveLamps:20})(doc);
for(const scene of doc.getRoot().listScenes())scene.setExtras({...scene.getExtras(),validationOnly:true});
await doc.transform(prune({propertyTypes:[PropertyType.NODE,PropertyType.MESH,PropertyType.ACCESSOR,PropertyType.MATERIAL],keepLeaves:true,keepAttributes:true}));
const output=path.join(outDir,'validation.glb');
await io.write(output,doc);
progress('checking all LODs after final compression');
const final=await io.read(output);
const report=await auditAtlasCoverage(final,outDir,{onProgress:progress});
await fs.writeFile(path.join(outDir,'coverage-final.json'),JSON.stringify(report));
if(!report.ok)throw Error(`final UV coverage failed: ${report.failures.length} entries`);
progress(`COVERAGE VALIDATION PASS: ${images.length} atlases; ${output}. Windows browser validation remains required.`);
